#!/usr/bin/env node
// A hand-written file above the tree's current edge is split before it becomes the next file nobody can read whole.

import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CEILING = 1734;

function git(args, input) {
  const result = spawnSync('git', args, { cwd: root, input, maxBuffer: 64 * 1024 * 1024 });
  if (result.status !== 0) throw new Error((result.stderr || Buffer.from('git failed')).toString('utf8').trim());
  return result.stdout;
}

function trackedFiles() {
  return git(['ls-files', '--stage', '-z'])
    .toString('utf8')
    .split('\0')
    .filter(Boolean)
    .map((entry) => entry.match(/^(\d+) [0-9a-f]+ 0\t([\s\S]+)$/))
    .filter((entry) => entry && (entry[1] === '100644' || entry[1] === '100755'))
    .map((entry) => entry[2]);
}

function textAttributes(files) {
  const input = Buffer.from(files.join('\0') + '\0');
  const fields = git(['check-attr', '-z', '--stdin', 'text'], input).toString('utf8').split('\0');
  const values = new Map();
  for (let at = 0; at + 2 < fields.length; at += 3) values.set(fields[at], fields[at + 2]);
  return values;
}

function isVendored(path) {
  return path.split('/').includes('vendor');
}

function isGenerated(text) {
  return (
    /^(?:<!doctype[^>]*>\s*)?<!--[\s\S]{0,400}?(generated|do not edit)/i.test(text) ||
    /^(#!.*\n)?\s*(\/\/|\/\*)[^\n]{0,300}?(generated|do not edit)/i.test(text) ||
    /^#[^\n]{0,300}?(generated|do not edit)/i.test(text)
  );
}

function logicalLines(text) {
  return text.split(/\r?\n/).filter((line) => line.trim()).length;
}

function oversized(entries) {
  return entries
    .filter((entry) => entry.textAttribute !== 'unset' && !isVendored(entry.path) && !isGenerated(entry.text))
    .map((entry) => ({ path: entry.path, lines: logicalLines(entry.text) }))
    .filter((entry) => entry.lines > CEILING)
    .sort((left, right) => right.lines - left.lines || left.path.localeCompare(right.path));
}

function assertDocumentedCeiling(guide) {
  const found = guide.match(/A hand-written text file is no more than ([\d,]+) lines\./);
  if (!found) throw new Error('AGENTS.md does not state the hand-written file ceiling');
  const documented = Number(found[1].replaceAll(',', ''));
  if (documented !== CEILING) throw new Error(`AGENTS.md says ${documented.toLocaleString('en-US')} lines; the check enforces ${CEILING.toLocaleString('en-US')}`);
}

function liveEntries() {
  const files = trackedFiles();
  const attributes = textAttributes(files);
  return files.map((path) => ({ path, textAttribute: attributes.get(path), text: readFileSync(join(root, path), 'utf8') }));
}

function selfTest() {
  const lines = (count, head = '') => head + Array.from({ length: count }, (_, at) => `line ${at + 1}`).join('\n');
  const entries = [
    { path: 'at-the-edge.rs', textAttribute: 'auto', text: lines(CEILING) },
    { path: 'over-by-one.rs', textAttribute: 'auto', text: lines(CEILING + 1) },
    { path: 'larger.rs', textAttribute: 'auto', text: lines(CEILING + 20) },
    { path: 'vendor/library.js', textAttribute: 'auto', text: lines(CEILING + 100) },
    { path: 'picture.png', textAttribute: 'unset', text: lines(CEILING + 100) },
    { path: 'built.html', textAttribute: 'auto', text: lines(CEILING + 100, '<!doctype html>\n<!-- Generated by the gallery. Do not edit. -->\n') },
    { path: 'built.js', textAttribute: 'auto', text: lines(CEILING + 100, '// Generated by the bundler. Do not edit.\n') },
    { path: 'Cargo.lock', textAttribute: 'auto', text: lines(CEILING + 100, '# This file is automatically @generated by Cargo.\n') },
  ];
  const got = oversized(entries);
  const want = [
    { path: 'larger.rs', lines: CEILING + 20 },
    { path: 'over-by-one.rs', lines: CEILING + 1 },
  ];
  if (JSON.stringify(got) !== JSON.stringify(want)) {
    throw new Error(`file-size self-test got ${JSON.stringify(got)}, want ${JSON.stringify(want)}`);
  }
  let drift = '';
  try {
    assertDocumentedCeiling('A hand-written text file is no more than 1,735 lines.');
  } catch (error) {
    drift = error.message;
  }
  if (!drift.includes('the check enforces 1,734')) throw new Error('file-size self-test did not refuse a different documented ceiling');
}

selfTest();
assertDocumentedCeiling(readFileSync(join(root, 'AGENTS.md'), 'utf8'));
const entries = liveEntries();
const failures = oversized(entries);
if (failures.length) {
  console.error(`hand-written text files may not exceed ${CEILING.toLocaleString('en-US')} lines:`);
  for (const failure of failures) console.error(`  ${failure.path}: ${failure.lines.toLocaleString('en-US')}`);
  process.exit(1);
}
console.log(`file sizes: ${entries.length} tracked files checked, none above ${CEILING.toLocaleString('en-US')} hand-written lines`);
